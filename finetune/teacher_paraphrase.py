"""Optional: ask a large model on Fireworks for more dispatcher phrasings.

Only QUESTIONS are generated by the teacher. Answers stay rule-written from
FACTS (dialog.py), so the teacher can't teach the student to make things up.
Anything too close to a held-out test question is dropped, so the test stays fair.

  export FIREWORKS_API_KEY=...
  python finetune/teacher_paraphrase.py --model <a large serverless chat model id> --per-intent 25
  python finetune/build_dataset.py        # picks up data/extra_questions.json

Read data/extra_questions.json before training: delete any line whose meaning
drifted to a different intent.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

from dialog import QUESTIONS, split_questions

OUT = Path(__file__).resolve().parent / "data" / "extra_questions.json"

INTENT_HINT = {
    "report": "opening question asking what the emergency is",
    "identity": "asking who or what is calling",
    "address": "asking for the address or building of the emergency",
    "location": "asking where the suspect is right now",
    "count": "asking how many people or suspects there are",
    "weapons": "asking about weapons",
    "describe": "asking for a description or clothing",
    "movement": "asking which direction the suspect is moving",
    "route": "asking where the suspect came from or has been",
    "injuries": "asking whether anyone is hurt",
    "who_subject": "asking who the suspect is or why they're doing it",
    "responders": "asking whether officers are responding and their ETA",
    "pressure_enroute": "pushing for a yes that officers are on the way",
    "pressure_onscene": "asking if officers have arrived on scene",
    "zone_alert": "asking whether people or buildings have been warned",
    "lockdown": "asking whether doors are locked or the building secured",
    "elapsed": "asking how long this has been going on",
    "status": "asking for a general update",
    "unanswerable": "asking something cameras can't know (sounds, cars, plates, phone numbers, rounds)",
    "repeat": "asking First Witness to repeat what it just said",
}


def toks(s: str) -> set[str]:
    return set(re.findall(r"[a-z']+", s.lower()))


def too_close(q: str, held: list[str]) -> bool:
    a = toks(q)
    for h in held:
        b = toks(h)
        if a and b and len(a & b) / len(a | b) >= 0.6:
            return True
    return False


def ask(model: str, key: str, intent: str, n: int) -> list[str]:
    examples = "\n".join(f"- {q}" for q in split_questions(intent, "train")[:6])
    prompt = (
        f"You write realistic lines a police or campus-security dispatcher says on a phone call with an "
        f"automated camera system during an incident. Write {n} different ways a dispatcher might be "
        f"{INTENT_HINT[intent]}. Vary length, tone, urgency and slang; some terse radio style, some full "
        f"sentences. Keep the same meaning. Examples:\n{examples}\n"
        f"Return ONLY a JSON array of strings."
    )
    body = {"model": model, "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.9, "max_tokens": 1500}
    req = urllib.request.Request("https://api.fireworks.ai/inference/v1/chat/completions",
                                 data=json.dumps(body).encode(),
                                 headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        text = json.loads(r.read())["choices"][0]["message"]["content"]
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S)
    m = re.search(r"\[.*\]", text, flags=re.S)
    return [q.strip() for q in json.loads(m.group(0)) if isinstance(q, str) and q.strip()] if m else []


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--per-intent", type=int, default=25)
    args = ap.parse_args()
    key = os.environ.get("FIREWORKS_API_KEY") or sys.exit("Set FIREWORKS_API_KEY")
    extra: dict[str, list[str]] = {}
    for intent in QUESTIONS:
        held = split_questions(intent, "heldout")
        got = ask(args.model, key, intent, args.per_intent)
        keep = sorted({q for q in got if not too_close(q, held) and len(q) < 160})
        extra[intent] = keep
        print(f"{intent:18s} kept {len(keep):3d} of {len(got)}")
    OUT.write_text(json.dumps(extra, indent=1))
    print(f"wrote {OUT}  -> now re-run build_dataset.py")


if __name__ == "__main__":
    main()
